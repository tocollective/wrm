let CELL_WIDTH: UWord = 8
let GLYPH_HEIGHT: UWord = 16
let GLYPH_WIDTH: UWord = 16
let GLYPH_ROW_BYTES: UWord = GLYPH_WIDTH / BYTE_BITS
let GLYPH_BYTES: UWord = GLYPH_ROW_BYTES * GLYPH_HEIGHT
let VIDEO_BUSY: UWord = 1
let VIDEO_ENABLE: UWord = 1
let VIDEO_MODE_640_480: UWord = 1
let VIDEO_8BPP: UWord = 2 << 4
let VIDEO_XY_SHIFT: UWord = 16
let VIDEO_FILL: UWord = 1
let VIDEO_COPY: UWord = 2
let VIDEO_EXPAND: UWord = 3
let PALETTE_BLACK: UWord = 0
let PALETTE_WHITE: UWord = 0xFFFFFF
let PALETTE_BACKGROUND: UWord = 0
let PALETTE_FOREGROUND: UWord = 1

let UNICODE_MAX: UWord = 0x10FFFF
let UNICODE_SURROGATE_MIN: UWord = 0xD800
let UNICODE_SURROGATE_MAX: UWord = 0xDFFF
let UNICODE_REPLACEMENT: UWord = 0xFFFD

let HEX_DIGIT_BITS: UWord = 4
let HEX_DIGIT_MASK: UWord = (1 << HEX_DIGIT_BITS) - 1
let HEX_WORD_DIGITS: UWord = WORD_BITS / HEX_DIGIT_BITS
let HEX_TOP_SHIFT: UWord = WORD_BITS - HEX_DIGIT_BITS
