let SUPERPAGE_SHIFT: UWord = 22
let SUPERPAGE_SIZE: UWord = 1 << SUPERPAGE_SHIFT
let PTBR_ENABLE: UWord = 1
let PTE_V: UWord = 1 << 0
let PTE_R: UWord = 1 << 1
let PTE_W: UWord = 1 << 2
let PTE_X: UWord = 1 << 3
let PTE_U: UWord = 1 << 4
let PTE_RWX_BITS: UWord = PTE_R | PTE_W | PTE_X
let PTE_RW: UWord = PTE_V | PTE_R | PTE_W
let PTE_RWX: UWord = PTE_RW | PTE_X
let PTE_RX: UWord = PTE_V | PTE_R | PTE_X
let PTE_RO: UWord = PTE_V | PTE_R
let TLBI_ALL: UWord = 2
let RAM_SLOT_COUNT: UWord = 4
let RAM_SLOT_MAX_BYTES: UWord = 32 * 1024 * 1024
let RAM_MAX_BYTES: UWord = RAM_SLOT_COUNT * RAM_SLOT_MAX_BYTES

let VRAM_BASE: UWord = 0xFC000000
let IO_BASE: UWord = 0xFD000000
let PIC_ENABLE: UWord = IO_BASE + WORD_BYTES
let UART_BASE: UWord = IO_BASE + 2 * PAGE_SIZE
let POWER_BASE: UWord = IO_BASE + 4 * PAGE_SIZE
let DISK0_BASE: UWord = IO_BASE + 5 * PAGE_SIZE
let DISK1_BASE: UWord = IO_BASE + 6 * PAGE_SIZE
let VIDEO_BASE: UWord = IO_BASE + 7 * PAGE_SIZE
let FLOPPY_BASE: UWord = IO_BASE + 8 * PAGE_SIZE
let RNG_BASE: UWord = IO_BASE + 14 * PAGE_SIZE
let RNG_SEEDED: UWord = 1

let BOOT_MAGIC: UWord = 0x424D5257
let BOOT_INFO_MAGIC: UWord = 0x4F464E49
let BOOT_INFO: UWord = 0x1000
let BOOT_INFO_END: UWord = BOOT_INFO + PAGE_SIZE
// Entry state at the end of the boot info page, within the signed offset(r0)
// field. Page zero stays unmapped, so a NULL access faults.
let KERNEL_SP: UWord = BOOT_INFO_END - 4 * WORD_BYTES
let KERNEL_STACK_BOTTOM: UWord = KERNEL_SP + WORD_BYTES
let KERNEL_STACK_TOP: UWord = KERNEL_STACK_BOTTOM + WORD_BYTES
let TRAP_SAVED_R1: UWord = KERNEL_STACK_TOP + WORD_BYTES
// Boot info and its device table must end below the entry state.
let BOOT_INFO_LIMIT: UWord = KERNEL_SP
let BOOT_INFO_BYTES: UWord = BOOT_INFO_LIMIT - BOOT_INFO
let BOOT_INFO_MIN_SIZE: UWord = 40
let BOOT_FIELD_MAGIC: UWord = 0
let BOOT_FIELD_SIZE: UWord = WORD_BYTES
let BOOT_FIELD_RAM_SIZE: UWord = 2 * WORD_BYTES
let BOOT_FIELD_DISK: UWord = 3 * WORD_BYTES
let BOOT_LOAD: UWord = 0x10000
let DEVICE_ENTRY_BYTES: UWord = 2 * WORD_BYTES
let SECTOR_SIZE: UWord = 512
let SECTOR_MASK: UWord = SECTOR_SIZE - 1
let DISK_PRESENT: UWord = 1 << 0
