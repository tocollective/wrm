// WRM hardware and boot ABI constants. defs.inc mirrors these for assembly;
// tests/test_kernel.py checks their values without generating code.
let BYTE_BITS: UWord = 8
let WORD_BYTES: UWord = 4
let WORD_BITS: UWord = 32
let WORD_MASK: UWord = 0xFFFFFFFF
let INSTRUCTION_BYTES: UWord = WORD_BYTES
let GPR_COUNT: UWord = 32
let REG_RESULT: UWord = 1
let REG_SP: UWord = 30
let REG_RA: UWord = 31
let STACK_ALIGNMENT: UWord = 8
let STACK_ALIGN_MASK: UWord = STACK_ALIGNMENT - 1
let KERNEL_STACK_BYTES: UWord = 8192
let TRAP_DISPATCH_HEADROOM: UWord = 512
// trapBadStack's own stack: the trusted kernel stack failed its checks.
let TRAP_EMERGENCY_STACK_BYTES: UWord = 2048
let STACK_CANARY: UWord = 0x4C414958

let CR_STATUS: UWord = 0
let CR_PTBR: UWord = 6
let STATUS_IE: UWord = 1 << 0
let STATUS_PIE: UWord = 1 << 1
let STATUS_UM: UWord = 1 << 2
let STATUS_PUM: UWord = 1 << 3
let STATUS_EXL: UWord = 1 << 4
let STATUS_SS: UWord = 1 << 5
let STATUS_PSS: UWord = 1 << 6
let STATUS_TRAP_RETURN_MASK: UWord = STATUS_PIE | STATUS_PUM | STATUS_EXL | STATUS_SS | STATUS_PSS
let FCSR_NX: UWord = 1 << 0
let FCSR_ROUND_UP: UWord = 3 << 5

let CAUSE_INTERRUPT: UWord = 0
let CAUSE_ILLEGAL_INSTRUCTION: UWord = 1
let CAUSE_MISALIGNED_FETCH: UWord = 2
